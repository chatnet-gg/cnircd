/*
 * Solanum: a slightly advanced ircd
 * cn_clone_except.c: per-host connection limit exceptions pushed by services
 *
 * A services pseudo-client keeps the list of hosts that may exceed the normal
 * per-host connection limit and sends it to the servers with ENCAP:
 *
 *     :<client> ENCAP * CLONEEXCEPT ADD <host> <max> [<by>]
 *     :<client> ENCAP * CLONEEXCEPT DEL <host>
 *     :<client> ENCAP * CLONEEXCEPT SYNCSTART   (full resend, e.g. after a burst)
 *     :<client> ENCAP * CLONEEXCEPT SYNCEND     (entries not re-added are dropped)
 *
 * The module keeps the list in memory and writes etc/exempt-cw.conf with one
 * class per distinct limit and one auth{} per host, then rehashes. The file is
 * only rewritten, and a rehash only requested, when its content changes, so a
 * full resync at every burst is harmless.
 *
 * Runtime auth items cannot be used instead: find_conf_by_address()
 * (ircd/hostmask.c) picks the item with the highest precedence, a counter that
 * decrements on every add, so an item added at runtime always loses against the
 * auth{} blocks read from ircd.conf. ircd.conf therefore has to include the
 * generated file before its generic auth{} blocks (earlier = higher
 * precedence):
 *
 *     .include "exempt-cw.conf"
 *
 * The file stays on disk, so a restarted server keeps its exceptions while
 * services are down.
 *
 * Oper command: CLONEEXCEPT LIST shows what this server has loaded.
 */

